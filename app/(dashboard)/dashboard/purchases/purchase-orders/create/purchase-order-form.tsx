"use client"

import type React from "react"
import { useState } from "react"
import { toast } from "sonner"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Label } from "@/components/ui/label"
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card"
import { Textarea } from "@/components/ui/textarea"
import LineItemsManager, { type LineItem } from "./line-items-manager"
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select"
import { createPurchaseOrder, updatePurchaseOrder } from "@/actions/purchase-order"
import { formatCurrency } from "../po-utils"
import ReceiptScanner, { ScannedPOData } from "./receipt-scanner"

// ── Types ──────────────────────────────────────────────────────────────────────

interface Supplier {
  id: string
  name: string
  contactPerson?: string
  email?: string
}

interface Item {
  id: string
  name: string
  sku: string
  description?: string
  unitCost?: number
}

interface DeliveryLocation {
  id: string
  name: string
  address?: string
}

interface PurchaseOrderFormProps {
  suppliers:             Supplier[]
  items:                 Item[]
  deliveryLocations:     DeliveryLocation[]
  autoGeneratedPONumber: string
  initialData?: {
    id:                   string
    poNumber:             string
    supplierId:           string
    orderDate:            string
    expectedDeliveryDate: string
    deliveryAddress:      string
    deliveryLocationId:   string
    notes?:               string
    shippingCost?:        string
    taxPercentage?:       number
    paymentTerms?:        string
    lineItems:            LineItem[]
    autoGeneratedPONumber: string
  }
  onSuccess?: (po: any) => void
  isLoading?: boolean
}

// ── Component ──────────────────────────────────────────────────────────────────

export default function PurchaseOrderForm({
  suppliers,
  items,
  deliveryLocations,
  initialData,
  autoGeneratedPONumber,
  onSuccess,
  isLoading = false,
}: PurchaseOrderFormProps) {
  const [formData, setFormData] = useState({
    poNumber:             initialData?.poNumber             || autoGeneratedPONumber,
    supplierId:           initialData?.supplierId           || "",
    // deliveryLocationId is now the DEFAULT/fallback — line items carry their own
    deliveryLocationId:   initialData?.deliveryLocationId   || "",
    orderDate:            initialData?.orderDate            || new Date().toISOString().split("T")[0],
    expectedDeliveryDate: initialData?.expectedDeliveryDate || "",
    deliveryAddress:      initialData?.deliveryAddress      || "",
    notes:                initialData?.notes                || "",
    shippingCost:         initialData?.shippingCost         || "0",
    taxPercentage:        initialData?.taxPercentage?.toString() || "0",
    paymentTerms:         initialData?.paymentTerms         || "",
  })

  const [lineItems,      setLineItems]      = useState<LineItem[]>(initialData?.lineItems || [])
  const [isSubmitting,   setIsSubmitting]   = useState(false)
  const [supplierSearch, setSupplierSearch] = useState("")

  // ── Receipt scanner handler ────────────────────────────────────────────────

  const handleExtracted = (data: ScannedPOData) => {
    setFormData(prev => ({
      ...prev,
      supplierId:           data.supplierId           || prev.supplierId,
      deliveryLocationId:   data.deliveryLocationId   || prev.deliveryLocationId,
      orderDate:            data.orderDate             || prev.orderDate,
      expectedDeliveryDate: data.expectedDeliveryDate  || prev.expectedDeliveryDate,
      deliveryAddress:      data.deliveryAddress       || prev.deliveryAddress,
      paymentTerms:         data.paymentTerms          || prev.paymentTerms,
      shippingCost:         data.shippingCost          || prev.shippingCost,
      notes: data.notes
        ? prev.notes
          ? `${prev.notes}\n${data.notes}`
          : data.notes
        : prev.notes,
    }))

    if (data.lineItems && data.lineItems.length > 0) {
      const mapped: LineItem[] = data.lineItems.map((li, idx) => ({
        id:           `scanned-${Date.now()}-${idx}`,
        itemId:       li.itemId    || "",
        itemName:     li.itemName  || "",
        itemSku:      li.itemSku   || "",
        quantity:     Number(li.quantity)  || 1,
        unitPrice:    Number(li.unitPrice) || 0,
        taxRate:      Number(li.taxRate)   || 0,
        lineTotal:    Number(li.lineTotal) ||
                      (Number(li.quantity) || 1) * (Number(li.unitPrice) || 0),
        // Scanned items get no location pre-set — user uses "Apply to all"
        locationId:   li.locationId   || "",
        locationName: li.locationName || "",
      }))

      setLineItems(mapped)

      const unmatched = mapped.filter(m => !m.itemId).length
      if (unmatched > 0) {
        toast.warning(`${unmatched} item(s) need manual selection`, {
          description: "Look for the amber warning on each unmatched row and pick the correct item.",
          duration: 6000,
        })
      } else {
        toast.success(`All ${mapped.length} items matched to your catalogue!`)
      }

      // Remind user to set locations if none came through from scanner
      const noLocation = mapped.filter(m => !m.locationId).length
      if (noLocation > 0) {
        toast.info(`Use "Apply to all" to set delivery locations`, {
          description: `${noLocation} row(s) have no location yet. Pick once and push to all.`,
          duration: 5000,
        })
      }
    } else {
      toast.warning("No line items were extracted", {
        description: "Try a clearer image or use Paste Text to enter receipt details manually.",
      })
    }
  }

  // ── Form helpers ───────────────────────────────────────────────────────────

  const handleInputChange = (
    e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>
  ) => {
    const { name, value } = e.target
    setFormData(prev => ({ ...prev, [name]: value }))
  }

  const handleSelectChange = (name: string, value: string) => {
    setFormData(prev => ({ ...prev, [name]: value }))
  }

  const calculateTotal = () => {
    const subtotal = lineItems.reduce((sum, item) => {
      const total =
        typeof item.lineTotal === "number"   ? item.lineTotal
        : typeof item.lineTotal === "string" ? parseFloat(item.lineTotal)
        : (item.lineTotal as any).toNumber?.() ?? 0
      return sum + total
    }, 0)
    return subtotal + (parseFloat(formData.shippingCost) || 0)
  }

  // ── Submit ─────────────────────────────────────────────────────────────────

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault()

    if (!formData.poNumber.trim()) { toast.error("PO Number is required");   return }
    if (!formData.supplierId)      { toast.error("Supplier is required");     return }
    if (lineItems.length === 0)    { toast.error("At least one line item is required"); return }

    const unmatchedItems = lineItems.filter(l => !l.itemId)
    if (unmatchedItems.length > 0) {
      toast.error(`${unmatchedItems.length} line item(s) have no item selected`, {
        description: "Please select an item for every row before saving.",
      })
      return
    }

    // Each line item uses its own locationId; fall back to the form-level default
    const itemsWithLocation = lineItems.map(li => ({
      ...li,
      locationId: li.locationId || formData.deliveryLocationId || undefined,
    }))

    const missingLocation = itemsWithLocation.filter(l => !l.locationId)
    if (missingLocation.length > 0) {
      toast.error(`${missingLocation.length} line item(s) have no delivery location`, {
        description: "Set a default location at the top of the form, or use 'Apply to all' in the line items section.",
      })
      return
    }

    setIsSubmitting(true)
    try {
      const data = {
        poNumber:             formData.poNumber,
        supplierId:           formData.supplierId,
        // Keep a top-level location for backward compat (first location used)
        deliveryLocationId:   itemsWithLocation[0]?.locationId ?? formData.deliveryLocationId,
        orderDate:            formData.orderDate,
        expectedDeliveryDate: formData.expectedDeliveryDate,
        deliveryAddress:      formData.deliveryAddress,
        notes:                formData.notes || undefined,
        shippingCost:         formData.shippingCost,
        taxPercentage:        parseInt(formData.taxPercentage) || 0,
        paymentTerms:         formData.paymentTerms || undefined,
        lineItems: itemsWithLocation.map(item => ({
          itemId:     item.itemId,
          quantity:   item.quantity,
          unitPrice:  item.unitPrice,
          taxRate:    item.taxRate,
          locationId: item.locationId,  // ← per-row location sent to backend
        })),
      }

      if (initialData?.id) {
        await updatePurchaseOrder(initialData.id, data)
        toast.success("Purchase Order updated successfully")
      } else {
        const result = await createPurchaseOrder(data)
        toast.success("Purchase Order created successfully")
        if (onSuccess) onSuccess(result.data)
      }
    } catch (error) {
      toast.error("Failed to save Purchase Order", {
        description: error instanceof Error ? error.message : "An error occurred",
      })
    } finally {
      setIsSubmitting(false)
    }
  }

  // ── Render ─────────────────────────────────────────────────────────────────

  return (
    <form onSubmit={handleSubmit} className="space-y-6">

      {/* Header Card */}
      <Card>
        <CardHeader>
          <div className="flex items-center justify-between gap-3 flex-wrap">
            <CardTitle>
              {initialData ? "Edit Purchase Order" : "Create Purchase Order"}
            </CardTitle>
            <ReceiptScanner
              availableItems={items}
              availableSuppliers={suppliers}
              availableLocations={deliveryLocations}
              onExtracted={handleExtracted}
            />
          </div>
          <p className="text-xs text-muted-foreground">
            Fill manually, or use{" "}
            <span className="font-medium text-emerald-600">Scan Receipt / Invoice</span>{" "}
            to auto-fill from a photo or pasted text.
          </p>
        </CardHeader>

        <CardContent className="space-y-4">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">

            {/* PO Number */}
            <div className="space-y-2">
              <Label htmlFor="poNumber">PO Number</Label>
              <Input
                id="poNumber" name="poNumber"
                value={formData.poNumber}
                onChange={handleInputChange}
                placeholder="PO-00001"
                disabled
                className="bg-muted"
              />
            </div>

            {/* Supplier */}
            <div className="space-y-2">
              <Label htmlFor="supplierId">Supplier *</Label>
              <Select
                value={formData.supplierId}
                onValueChange={v => handleSelectChange("supplierId", v)}
                disabled={isSubmitting || isLoading}
              >
                <SelectTrigger id="supplierId">
                  <SelectValue placeholder="Select supplier…" />
                </SelectTrigger>
                <SelectContent>
                  <div className="p-2 border-b sticky top-0 bg-background z-50">
                    <Input
                      placeholder="Search suppliers…"
                      value={supplierSearch}
                      onChange={e => setSupplierSearch(e.target.value)}
                      onClick={e => e.stopPropagation()}
                      className="h-8"
                    />
                  </div>
                  {suppliers
                    .filter(s => s.name.toLowerCase().includes(supplierSearch.toLowerCase()))
                    .map(s => (
                      <SelectItem key={s.id} value={s.id}>{s.name}</SelectItem>
                    ))}
                  {suppliers.filter(s =>
                    s.name.toLowerCase().includes(supplierSearch.toLowerCase())
                  ).length === 0 && (
                    <div className="p-4 text-center text-sm text-muted-foreground">No suppliers found</div>
                  )}
                </SelectContent>
              </Select>
            </div>

            {/* Default Delivery Location (fallback for all line items) */}
            <div className="space-y-2">
              <Label htmlFor="deliveryLocationId">
                Default Delivery Location
                <span className="ml-1 text-xs text-muted-foreground font-normal">
                  (applied to line items with no location set)
                </span>
              </Label>
              <Select
                value={formData.deliveryLocationId || "__none__"}
                onValueChange={v => handleSelectChange("deliveryLocationId", v === "__none__" ? "" : v)}
                disabled={isSubmitting || isLoading}
              >
                <SelectTrigger id="deliveryLocationId">
                  <SelectValue placeholder="Select default location…" />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="__none__">— None (set per line item) —</SelectItem>
                  {deliveryLocations.map(l => (
                    <SelectItem key={l.id} value={l.id}>{l.name}</SelectItem>
                  ))}
                </SelectContent>
              </Select>
              <p className="text-xs text-muted-foreground">
                You can also override the location per line item below, or use "Apply to all".
              </p>
            </div>

            {/* Order Date */}
            <div className="space-y-2">
              <Label htmlFor="orderDate">Order Date</Label>
              <Input
                id="orderDate" name="orderDate" type="date"
                value={formData.orderDate}
                onChange={handleInputChange}
                disabled={isSubmitting || isLoading}
              />
            </div>

            {/* Expected Delivery Date */}
            <div className="space-y-2">
              <Label htmlFor="expectedDeliveryDate">Expected Delivery Date</Label>
              <Input
                id="expectedDeliveryDate" name="expectedDeliveryDate" type="date"
                value={formData.expectedDeliveryDate}
                onChange={handleInputChange}
                disabled={isSubmitting || isLoading}
              />
            </div>
          </div>

          {/* Delivery Address */}
          <div className="space-y-2">
            <Label htmlFor="deliveryAddress">Delivery Address</Label>
            <Textarea
              id="deliveryAddress" name="deliveryAddress"
              value={formData.deliveryAddress}
              onChange={handleInputChange}
              placeholder="Enter delivery address…"
              disabled={isSubmitting || isLoading}
              rows={3}
            />
          </div>

          {/* Notes */}
          <div className="space-y-2">
            <Label htmlFor="notes">Notes</Label>
            <Textarea
              id="notes" name="notes"
              value={formData.notes}
              onChange={handleInputChange}
              placeholder="Add any additional notes…"
              disabled={isSubmitting || isLoading}
              rows={2}
            />
          </div>
        </CardContent>
      </Card>

      {/* Line Items — now with per-row location + bulk apply */}
      <LineItemsManager
        lineItems={lineItems}
        onLineItemsChange={setLineItems}
        availableItems={items}
        locations={deliveryLocations}   // ← pass all locations down
        disabled={isSubmitting || isLoading}
      />

      {/* Additional Info */}
      <Card>
        <CardHeader><CardTitle>Additional Information</CardTitle></CardHeader>
        <CardContent className="space-y-4">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="space-y-2">
              <Label htmlFor="shippingCost">Shipping Cost</Label>
              <Input
                id="shippingCost" name="shippingCost" type="number" step="0.01" min="0"
                value={formData.shippingCost}
                onChange={handleInputChange}
                placeholder="0.00"
                disabled={isSubmitting || isLoading}
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="taxPercentage">Tax Percentage (%)</Label>
              <Input
                id="taxPercentage" name="taxPercentage" type="number" step="0.01" min="0" max="100"
                value={formData.taxPercentage}
                onChange={handleInputChange}
                placeholder="0"
                disabled={isSubmitting || isLoading}
              />
            </div>
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="paymentTerms">Payment Terms</Label>
              <Input
                id="paymentTerms" name="paymentTerms"
                value={formData.paymentTerms}
                onChange={handleInputChange}
                placeholder="e.g., Net 30, COD"
                disabled={isSubmitting || isLoading}
              />
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Total */}
      <Card className="bg-muted">
        <CardContent className="pt-6 flex justify-between items-center text-lg">
          <span className="font-semibold">Total:</span>
          <span className="text-2xl font-bold">{formatCurrency(calculateTotal())}</span>
        </CardContent>
      </Card>

      {/* Submit */}
      <div className="flex gap-3 justify-end">
        <Button
          type="submit"
          disabled={isSubmitting || isLoading}
          size="lg"
          className="gap-2"
        >
          {isSubmitting || isLoading ? "Saving…" : "Save Purchase Order"}
        </Button>
      </div>
    </form>
  )
}