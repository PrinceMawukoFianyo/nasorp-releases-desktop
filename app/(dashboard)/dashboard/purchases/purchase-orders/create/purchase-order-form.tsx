"use client"

import type React from "react"
import { useState, useEffect } from "react"
import { toast } from "sonner"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Label } from "@/components/ui/label"
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card"
import { Textarea } from "@/components/ui/textarea"
import LineItemsManager, { type LineItem } from "./line-items-manager"
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select"
import { createPurchaseOrder, updatePurchaseOrder } from "@/actions/purchase-order"
import { formatCurrency } from "../po-utils"
import { FormControl, FormField, FormItem, FormLabel, FormMessage } from "@/components/ui/form"

interface supplier {
  id: string
  name: string
  contactPerson?: string
  email?: string
}

interface Item {
  id: string
  name: string
  sku: string
  description?: string
  unitCost?: number
}

// Add DeliveryLocation interface
interface DeliveryLocation {
  id: string
  name: string
  address?: string
}

interface PurchaseOrderFormProps {
  suppliers: supplier[]
  items: Item[]
  deliveryLocations: DeliveryLocation[]
  autoGeneratedPONumber: string // ✅ Add this line
  initialData?: {
    id: string
    poNumber: string
    supplierId: string
    orderDate: string
    expectedDeliveryDate: string
    deliveryAddress: string
    deliveryLocationId: string
    notes?: string
    shippingCost?: string
    taxPercentage?: number
    paymentTerms?: string
    lineItems: LineItem[]
    autoGeneratedPONumber: string
  }
  onSuccess?: (po: any) => void
  isLoading?: boolean
}
export default function PurchaseOrderForm({
  suppliers,
  items,
  deliveryLocations, // Add this
  initialData,
  autoGeneratedPONumber,
  onSuccess,
  isLoading = false,
}: PurchaseOrderFormProps) {
 const [formData, setFormData] = useState({
    poNumber: initialData?.poNumber || autoGeneratedPONumber, 
    supplierId: initialData?.supplierId || "",
    deliveryLocationId: initialData?.deliveryLocationId || "",
    orderDate: initialData?.orderDate || new Date().toISOString().split("T")[0],
    expectedDeliveryDate: initialData?.expectedDeliveryDate || "",
    deliveryAddress: initialData?.deliveryAddress || "",
    notes: initialData?.notes || "",
    shippingCost: initialData?.shippingCost || "0",
    taxPercentage: initialData?.taxPercentage?.toString() || "0",
    paymentTerms: initialData?.paymentTerms || "",
  })

  const [lineItems, setLineItems] = useState<LineItem[]>(
    initialData?.lineItems || []
  )
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [supplierSearch, setsupplierSearch] = useState("")
  const [locationSearch, setLocationSearch] = useState("");

  const handleInputChange = (
    e: React.ChangeEvent<
      HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement
    >
  ) => {
    const { name, value } = e.target
    setFormData((prev) => ({ ...prev, [name]: value }))
  }

  const handleSelectChange = (name: string, value: string) => {
    setFormData((prev) => ({ ...prev, [name]: value }))
  }

  const calculateTotal = () => {
    const subtotal = lineItems.reduce((sum, item) => {
      const total = typeof item.lineTotal === "number"
        ? item.lineTotal
        : typeof item.lineTotal === "string"
        ? parseFloat(item.lineTotal)
        : item.lineTotal.toNumber()
      return sum + total
    }, 0)
    const shippingCost = parseFloat(formData.shippingCost) || 0
    return subtotal + shippingCost
  }

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault()

    if (!formData.poNumber.trim()) {
      toast.error("PO Number is required")
      return
    }

    if (!formData.supplierId) {
      toast.error("supplier is required")
      return
    }

    if (!formData.deliveryLocationId) {
      toast.error("Delivery Location is required")
      return
    }

    if (lineItems.length === 0) {
      toast.error("At least one line item is required")
      return
    }

    setIsSubmitting(true)

    try {
      const data = {
        poNumber: formData.poNumber,
        supplierId: formData.supplierId,
        deliveryLocationId: formData.deliveryLocationId, // Add this field
        orderDate: formData.orderDate,
        expectedDeliveryDate: formData.expectedDeliveryDate,
        deliveryAddress: formData.deliveryAddress,
        notes: formData.notes || undefined,
        shippingCost: formData.shippingCost,
        taxPercentage: parseInt(formData.taxPercentage) || 0,
        paymentTerms: formData.paymentTerms || undefined,
        lineItems: lineItems.map((item) => ({
          itemId: item.itemId,
          quantity: item.quantity,
          unitPrice: item.unitPrice,
          taxRate: item.taxRate,
        })),
      }

      if (initialData?.id) {
        await updatePurchaseOrder(initialData.id, data)
        toast.success("Purchase Order updated successfully")
      } else {
        const result = await createPurchaseOrder(data)
        toast.success("Purchase Order created successfully")
        if (onSuccess) {
          onSuccess(result.data)
        }
      }
    } catch (error) {
      toast.error("Failed to save Purchase Order", {
        description: error instanceof Error ? error.message : "An error occurred",
      })
    } finally {
      setIsSubmitting(false)
    }
  }

  return (
    <form onSubmit={handleSubmit} className="space-y-6">
      {/* Header Section */}
      <Card>
        <CardHeader>
          <CardTitle>
            {initialData ? "Edit Purchase Order" : "Create Purchase Order"}
          </CardTitle>
        </CardHeader>
        <CardContent className="space-y-4">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {/* PO Number */}
            <div className="space-y-2">
              <Label htmlFor="poNumber">PO Number</Label>
              <Input
                id="poNumber"
                name="poNumber"
                value={formData.poNumber}
                onChange={handleInputChange}
                placeholder="PO-00001"
                disabled={true} // ✅ Always disabled since it's auto-generated
                required
                className="bg-muted" // ✅ Optional: visual indicator it's disabled
              />
            </div>

            {/* supplier */}
            <div className="space-y-2">
              <Label htmlFor="supplierId">supplier</Label>
              <Select
                value={formData.supplierId}
                onValueChange={(value) =>
                  handleSelectChange("supplierId", value)
                }
                disabled={isSubmitting || isLoading}
              >
                <SelectTrigger id="supplierId">
                  <SelectValue placeholder="Select supplier..." />
                </SelectTrigger>
                <SelectContent>
                  {/* ✅ Search input */}
                  <div className="p-2 border-b sticky top-0 bg-background z-50">
                    <Input
                      placeholder="Search suppliers..."
                      value={supplierSearch}
                      onChange={(e) => setsupplierSearch(e.target.value)}
                      onClick={(e) => e.stopPropagation()}
                      className="h-8"
                    />
                  </div>
                  
                  {/* ✅ Filtered suppliers */}
                  {suppliers
                    .filter((supplier) =>
                      supplier.name.toLowerCase().includes(supplierSearch.toLowerCase())
                    )
                    .map((supplier) => (
                      <SelectItem key={supplier.id} value={supplier.id}>
                        {supplier.name}
                      </SelectItem>
                    ))}
                  
                  {/* ✅ No results message */}
                  {suppliers.filter((supplier) =>
                    supplier.name.toLowerCase().includes(supplierSearch.toLowerCase())
                  ).length === 0 && (
                    <div className="p-4 text-center text-sm text-muted-foreground">
                      No suppliers found
                    </div>
                  )}
                </SelectContent>
              </Select>
            </div>
            {/* Delivery Location - NEW FIELD */}
           <div className="space-y-2">
            <Label htmlFor="deliveryLocationId">Delivery Location *</Label>
            <Select
              value={formData.deliveryLocationId}
              onValueChange={(value) =>
                handleSelectChange("deliveryLocationId", value)
              }
              disabled={isSubmitting || isLoading}
            >
              <SelectTrigger id="deliveryLocationId">
                <SelectValue placeholder="Select delivery location..." />
              </SelectTrigger>
              <SelectContent>
                {/* ✅ Search input */}
                <div className="p-2 border-b sticky top-0 bg-background z-50">
                  <Input
                    placeholder="Search locations..."
                    value={locationSearch}
                    onChange={(e) => setLocationSearch(e.target.value)}
                    onClick={(e) => e.stopPropagation()}
                    className="h-8"
                  />
                </div>
                
                {/* ✅ Filtered locations */}
                {deliveryLocations
                  .filter((location) =>
                    location.name.toLowerCase().includes(locationSearch.toLowerCase())
                  )
                  .map((location) => (
                    <SelectItem key={location.id} value={location.id}>
                      {location.name}
                      {location.address && ` - ${location.address}`}
                    </SelectItem>
                  ))}
                
                {/* ✅ No results message */}
                {deliveryLocations.filter((location) =>
                  location.name.toLowerCase().includes(locationSearch.toLowerCase())
                ).length === 0 && (
                  <div className="p-4 text-center text-sm text-muted-foreground">
                    No locations found
                  </div>
                )}
              </SelectContent>
            </Select>
          </div>
            {/* Order Date */}
            <div className="space-y-2">
              <Label htmlFor="orderDate">Order Date</Label>
              <Input
                id="orderDate"
                name="orderDate"
                type="date"
                value={formData.orderDate}
                onChange={handleInputChange}
                disabled={isSubmitting || isLoading}
              />
            </div>

            {/* Expected Delivery Date */}
            <div className="space-y-2">
              <Label htmlFor="expectedDeliveryDate">
                Expected Delivery Date
              </Label>
              <Input
                id="expectedDeliveryDate"
                name="expectedDeliveryDate"
                type="date"
                value={formData.expectedDeliveryDate}
                onChange={handleInputChange}
                disabled={isSubmitting || isLoading}
              />
            </div>
          </div>

          {/* Delivery Address */}
          <div className="space-y-2">
            <Label htmlFor="deliveryAddress">Delivery Address</Label>
            <Textarea
              id="deliveryAddress"
              name="deliveryAddress"
              value={formData.deliveryAddress}
              onChange={handleInputChange}
              placeholder="Enter delivery address..."
              disabled={isSubmitting || isLoading}
              rows={3}
            />
          </div>

          {/* Notes */}
          <div className="space-y-2">
            <Label htmlFor="notes">Notes</Label>
            <Textarea
              id="notes"
              name="notes"
              value={formData.notes}
              onChange={handleInputChange}
              placeholder="Add any additional notes..."
              disabled={isSubmitting || isLoading}
              rows={2}
            />
          </div>
        </CardContent>
      </Card>

      {/* Line Items Section */}
      <LineItemsManager
        lineItems={lineItems}
        onLineItemsChange={setLineItems}
        availableItems={items}
        disabled={isSubmitting || isLoading}
      />

      {/* Additional Costs Section */}
      <Card>
        <CardHeader>
          <CardTitle>Additional Information</CardTitle>
        </CardHeader>
        <CardContent className="space-y-4">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {/* Shipping Cost */}
            <div className="space-y-2">
              <Label htmlFor="shippingCost">Shipping Cost</Label>
              <Input
                id="shippingCost"
                name="shippingCost"
                type="number"
                step="0.01"
                min="0"
                value={formData.shippingCost}
                onChange={handleInputChange}
                placeholder="0.00"
                disabled={isSubmitting || isLoading}
              />
            </div>

            {/* Tax Percentage */}
            <div className="space-y-2">
              <Label htmlFor="taxPercentage">Tax Percentage (%)</Label>
              <Input
                id="taxPercentage"
                name="taxPercentage"
                type="number"
                step="0.01"
                min="0"
                max="100"
                value={formData.taxPercentage}
                onChange={handleInputChange}
                placeholder="0"
                disabled={isSubmitting || isLoading}
              />
            </div>

            {/* Payment Terms */}
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="paymentTerms">Payment Terms</Label>
              <Input
                id="paymentTerms"
                name="paymentTerms"
                value={formData.paymentTerms}
                onChange={handleInputChange}
                placeholder="e.g., Net 30, COD"
                disabled={isSubmitting || isLoading}
              />
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Total Section */}
      <Card className="bg-muted">
        <CardContent className="pt-6 flex justify-between items-center text-lg">
          <span className="font-semibold">Total:</span>
          <span className="text-2xl font-bold">
            {formatCurrency(calculateTotal())}
          </span>
        </CardContent>
      </Card>

      {/* Submit Button */}
      <div className="flex gap-3 justify-end">
        <Button
          type="submit"
          disabled={isSubmitting || isLoading}
          size="lg"
          className="gap-2"
        >
          {isSubmitting || isLoading ? "Saving..." : "Save Purchase Order"}
        </Button>
      </div>
    </form>
  )
}